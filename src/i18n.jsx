const translations = { en, ne, bo }

const LanguageContext = createContext(null)

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => {
    try {
      return localStorage.getItem('tms-lang') || 'en'
    } catch {
      return 'en'
    }
  })

  useEffect(() => {
    document.documentElement.lang = lang
    try {
      localStorage.setItem('tms-lang', lang)
    } catch {
      /* no-op */
    }
  }, [lang])

  const value = useMemo(() => {
    const dict = translations[lang] || translations.en
    const t = (key, fallback) => {
      const node = key.split('.').reduce((acc, part) => (acc == null ? acc : acc[part]), dict)
      if (typeof node === 'string') return node
      const enNode = key.split('.').reduce((acc, part) => (acc == null ? acc : acc[part]), translations.en)
      if (typeof enNode === 'string') return enNode
      return fallback ?? key
    }
    return { lang, setLang, t, langs: ['en', 'ne', 'bo'] }
  }, [lang])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const ctx = useContext(LanguageContext)
  if (!ctx) throw new Error('useLanguage must be used within LanguageProvider')
  return ctx
}
